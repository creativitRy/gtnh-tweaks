import { applyPatch, type StructuredPatch } from 'diff';
import { DefaultKeys } from './defaultkeys';
import { ServerRanks } from './serverRanks';
import { GTNH_VERSIONS_LOOKUP } from './data/versions';
import { downloadGtnhConfig } from './githubDownloader';
import type { SelectedTweaksMap, TweakDef } from './tweak';

export class DownloadContext {
  private readonly createdFiles = new Map<string, string | Blob>();
  private readonly modifiedFiles = new Map<string, string>();
  private readonly deletedFiles = new Set<string>();
  private serverRanksEnabled = false;

  constructor(
    readonly version: string,
    readonly selections: SelectedTweaksMap,
    readonly ALL_TWEAKS: Map<string, TweakDef>,
  ) {}

  get created(): ReadonlyMap<string, string | Blob> {
    return this.createdFiles;
  }

  get modified(): ReadonlyMap<string, string> {
    return this.modifiedFiles;
  }

  get deleted(): ReadonlySet<string> {
    return this.deletedFiles;
  }

  createRawFile(filePath: string, content: string | Blob): void {
    if (this.createdFiles.has(filePath)) throw new Error(`File ${filePath} was already created`);
    this.createdFiles.set(filePath, content);
  }

  /** Registers an empty file that is listed in the download but not included in the zip. */
  addPlaceholder(filePath: string): void {
    this.createdFiles.set(filePath, '');
  }

  async patchFile(filePath: string, patch: string | StructuredPatch | [StructuredPatch]): Promise<void> {
    let prev = this.modifiedFiles.get(filePath);
    if (prev === undefined) {
      prev = await this.download(filePath);
    }
    const patchResult = applyPatch(prev, patch, { fuzzFactor: 16, autoConvertLineEndings: true });
    if (patchResult === false) {
      throw new Error(`Failed to apply patch to ${filePath}.\nPatch:\n${patch}\n\nFile:\n${prev}`);
    }
    this.modifiedFiles.set(filePath, patchResult);
  }

  /**
   *
   * @param key
   * @param value value to set (https://minecraft.wiki/w/Key_codes#Before_1.13). If undefined, remove the key(s).
   */
  patchDefaultKeybind(key: string, value: number | undefined): void {
    const filePath = '.minecraft/config/defaultkeys.txt';
    let prevRaw = this.createdFiles.get(filePath);
    if (prevRaw === undefined) {
      prevRaw = ``;
    } else if (typeof prevRaw !== 'string') throw new Error(`Unexpected type for ${filePath}`);
    const keybinds = new DefaultKeys(prevRaw);
    keybinds.patch(key, value);
    this.createdFiles.set(filePath, keybinds.generate());
  }

  /**
   *
   * @param rankName if undefined, change all ranks
   * @param key
   * @param value value to set. If undefined, remove the key(s).
   */
  async patchServerRanks(rankName: string | undefined, key: string, value: string | undefined): Promise<void> {
    if (!this.serverRanksEnabled) {
      this.serverRanksEnabled = true;
      await this.patchFile(
        '.minecraft/serverutilities/serverutilities.cfg',
        `Index: .minecraft/serverutilities/serverutilities.cfg
===================================================================
--- .minecraft/serverutilities/serverutilities.cfg
+++ .minecraft/serverutilities/serverutilities.cfg
@@ -331,9 +331,9 @@
 ranks {
     # Add permissions for commands and allow them to be controlled by ranks. [default: true]
     B:command_permissions=true
 
     # Enables Ranks. [default: true]
-    B:enabled=false
+    B:enabled=true
 
     # Adds chat colors/rank-specific syntax. [default: true]
     B:override_chat=true
}`,
      );
    }
    const filePath = '.minecraft/serverutilities/server/ranks.txt';
    let prevRaw = this.modifiedFiles.get(filePath);
    if (prevRaw === undefined) {
      prevRaw = await this.download(filePath);
    }
    const ranks = new ServerRanks(prevRaw);
    ranks.patch(rankName, key, value);
    this.modifiedFiles.set(filePath, ranks.generate());
  }

  collectDeletions(): ReadonlySet<string> {
    for (const [id, tweakConfig] of Object.entries(this.selections)) {
      const tweak = this.ALL_TWEAKS.get(id)!;
      for (const file of tweak.filesToDelete ? tweak.filesToDelete(this.version, tweakConfig) : []) {
        this.deletedFiles.add(file);
      }
    }
    return this.deletedFiles;
  }

  buildManifest(sourceUrl: string): string {
    const list = (paths: Iterable<string>) =>
      [...paths]
        .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }))
        .map(f => `\n  - ${f}`)
        .join('');
    return `${sourceUrl}

This file was generated by GTNH Tweaks.

- Modpack Version:
  - ${this.version}
- Selected Tweaks:
${Object.keys(this.selections)
  .map(id => `  - ${id}`)
  .sort()
  .join('\n')}
- Created Files:${list(this.createdFiles.keys())}
- Modified files:${list(this.modifiedFiles.keys())}
- Deleted Files:${list(this.deletedFiles)}
`;
  }

  protected download(filePath: string): Promise<string> {
    return downloadGtnhConfig(GTNH_VERSIONS_LOOKUP.get(this.version)!.gitCommit, filePath);
  }
}
